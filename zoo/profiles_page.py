"""docs/PROFILES.md: what the owner can ask the zoo for.

Generated from catalogue/shortcuts.json and the catalogue, so it cannot
drift: `python3 -m zoo.profiles_page` rewrites it, and a test fails when
the committed page differs from what this module writes.
"""
import collections
import json
from pathlib import Path

from . import catalogue as cat_mod

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / 'docs/PROFILES.md'
RUNS = 'https://github.com/diegoami/borg-zoo/actions/runs/'
ISSUES = 'https://github.com/diegoami/borg-zoo/issues/'

# What each setting the owner has varied means, and what the runs showed.
LESSONS = {
    'borg_plan': ('The errands plan the Borg follows. Loop-levels plans up to `d3ebe3c0`: the errands plan '
                  'added caster deaths with the town planner (borg-cemetery#19). Max-depth caps from '
                  '`6d1bca10` (#440): a cap is a preparation check, not a hard limit; 35 of 900 games died '
                  'or ended below it (#147).'),
    'borg_town_plan': ('"New inventory": the live town planner. Alone it looked best in the #123 small tier '
                       '(15 deaths v control 22 of 90).'),
    'borg_trip_policy': ("Extra reasons to return to town. Barely changes play: 42 of 54 paired pilot games "
                         "identical. Kept off in #123's development arms until it is shown to help (owner). "
                         "From `8a0b57c8` it is borg-rs#88's additive policy."),
    'borg_trip_unknown_stacks': ('Return when this many carried stacks are unidentified (default 4). Changes '
                                 'play: (3,x) differs from return-off in about 40% of games; (5,1) played like '
                                 'return-off in 26-27 of 30 starts.'),
    'borg_trip_pack_slack': ('Return when this few pack slots are free (default 2). Almost no effect: 1 and 2 '
                             'played identical keys in 359 of 360 #147 games.'),
    'borg_param_caution_heal_when_outmatched': ('A hurt Borg in lethal danger with no escape drinks its best '
                                                'cure potion (#151). Waits for borg-reborn-rs #461.'),
}


def shortcuts(root=ROOT):
    return json.loads((Path(root) / 'catalogue/shortcuts.json').read_text())['shortcuts']


def check(cat, sc):
    """Problems with the shortcuts: unknown profiles or specimens."""
    bad = []
    for name, s in sc.items():
        bad += [f'{name}: unknown profile {p}' for p in s['profiles'] if p not in cat['profiles']]
        bad += [f"{name}: unknown specimen {r['specimen']}" for r in s.get('runs', [])
                if r['specimen'] not in cat['specimens']['specimens']]
    return bad


def value(v):
    return cat_mod.setting_value(v) if not isinstance(v, str) or v else '""'


def varying(cat, profiles):
    """Per profile, only the settings that differ within the set."""
    settings = [cat['profiles'][p].get('settings', {}) for p in profiles]
    keys = sorted({k for s in settings for k in s})
    vary = [k for k in keys if len({json.dumps(s.get(k)) for s in settings}) > 1]
    common = {k: settings[0][k] for k in keys if k not in vary and k in settings[0]}
    return vary, common


def render(cat, sc):
    out = ['# What you can ask the zoo for', '',
           '*Generated by `python3 -m zoo.profiles_page` from `catalogue/shortcuts.json` and the '
           'catalogue. Do not edit by hand.*', '',
           'Ask for a run by shortcut, ref and tier, for example: **"small run of `maxdepth-2x5` on '
           'borg-reborn-rs `<sha>`"**. Every study grows pilot → small → medium → big → full, one tier '
           'at a time (RULES 14). A new shortcut is an entry in `catalogue/shortcuts.json`.', '',
           '## Shortcuts', '',
           '| Shortcut | Issue | Arms | Status | What |', '| --- | --- | ---: | --- | --- |']
    for name, s in sc.items():
        out.append(f"| `{name}` | [#{s['issue']}]({ISSUES}{s['issue']}) | {len(s['profiles'])} | "
                   f"{s['status']} | {s['what']} |")
    for name, s in sc.items():
        vary, common = varying(cat, s['profiles'])
        out += ['', f'### `{name}`', '', s['what'], '']
        if common:
            out.append('Every arm: ' + ', '.join(f'`{k} = {value(v)}`' for k, v in common.items()) + '.')
            out.append('')
        if vary:
            out.append('| Profile | ' + ' | '.join(f'`{k}`' for k in vary) + ' |')
            out.append('| --- |' + ' --- |' * len(vary))
            for p in s['profiles']:
                st = cat['profiles'][p].get('settings', {})
                out.append(f'| `{p}` | ' + ' | '.join(value(st[k]) if k in st else '–' for k in vary) + ' |')
        else:
            out.append('Profiles: ' + ', '.join(f'`{p}`' for p in s['profiles']) + '.')
        if s.get('runs'):
            out += ['', '| Run | Tier | Specimen | Result |', '| --- | --- | --- | --- |']
            for r in s['runs']:
                out.append(f"| [{r['run']}]({RUNS}{r['run']}) | {r['tier']} | `{r['specimen']}` | {r['result']} |")
    asked = collections.defaultdict(lambda: (set(), []))
    for name, s in sc.items():
        vary, _ = varying(cat, s['profiles'])
        for k in vary:
            vals, where = asked[k]
            vals.update(value(cat['profiles'][p].get('settings', {})[k]) if k in cat['profiles'][p].get('settings', {})
                        else 'not set' for p in s['profiles'])
            where.append(f'`{name}`')
    out += ['', '## Settings you have built arms with', '',
            'Only the settings that differ between the arms of a shortcut.', '',
            '| Setting | Values used | Shortcuts | What it does, and what we learned |', '| --- | --- | --- | --- |']
    for k in sorted(asked, key=lambda k: (k not in LESSONS, list(LESSONS).index(k) if k in LESSONS else 0, k)):
        vals, where = asked[k]
        vals = sorted(vals, key=lambda x: (x == 'not set', not x.lstrip('-').isdigit(),
                                           int(x) if x.lstrip('-').isdigit() else 0, x))
        out.append(f"| `{k}` | {', '.join(vals)} | {', '.join(where)} | {LESSONS.get(k, '')} |")
    specs = cat['specimens']['specimens']
    used = []
    for s in sc.values():
        for r in s.get('runs', []):
            if r['specimen'] not in used:
                used.append(r['specimen'])
    out += ['', '## Specimens behind the shortcuts', '',
            '| Specimen | Repository | Ref | What it is |', '| --- | --- | --- | --- |']
    for name in used:
        spec = specs[name]
        label = spec.get('label', '').split('. ')[0].rstrip('.')
        out.append(f"| `{name}` | {spec.get('repository', '')} | `{spec['ref'][:8]}` | {label}. |")
    return '\n'.join(out) + '\n'


def main():
    cat = cat_mod.catalogue()
    sc = shortcuts()
    bad = check(cat, sc)
    if bad:
        raise SystemExit('\n'.join(bad))
    PAGE.write_text(render(cat, sc))
    print(f'{PAGE.relative_to(ROOT)}: {len(sc)} shortcuts')


if __name__ == '__main__':
    main()
