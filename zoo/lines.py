"""Which line of borg-reborn-rs each specimen is on, and how far behind its head.

borg-reborn-rs has two lines (borg-zoo#645): `track-p`, the working line, and `main`, which receives reviewed
milestone merges. A result is tied to its exact source (RULES.md 14), so an experiment's "current build" has to name a
line, and a specimen that is behind its line's head says so here.

    python3 -m zoo.lines                 # the heads, then every borg-reborn-rs specimen (newest 40)
    python3 -m zoo.lines --match f5749   # only specimens whose name or ref contains the text
    python3 -m zoo.lines --all           # every specimen
    python3 -m zoo.lines --write         # write docs/LINES.md (the newest 60; add --all for every specimen)

It asks GitHub (`gh api .../compare`), so it needs `gh` and network.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = 'diegoami/borg-reborn-rs'
LINES = ('track-p', 'main')


def gh(path):
    out = subprocess.run(['gh', 'api', path], capture_output=True, text=True)
    if out.returncode != 0:
        return None
    return json.loads(out.stdout)


def heads():
    return {line: (gh(f'repos/{REPO}/commits/{line}') or {}).get('sha') for line in LINES}


def position(ref, head):
    """How a specimen's ref stands against a line's head: 'at head', 'behind N', 'ahead N' or 'diverged'."""
    if not ref or not head:
        return 'unknown'
    if ref == head:
        return 'at head'
    c = gh(f'repos/{REPO}/compare/{ref}...{head}')
    if c is None:
        return 'unknown'
    status, ahead, behind = c.get('status'), c.get('ahead_by', 0), c.get('behind_by', 0)
    if status == 'ahead':
        return f'behind {ahead}'
    if status == 'behind':
        return f'ahead {behind}'
    if status == 'identical':
        return 'at head'
    return f'diverged (+{behind} / -{ahead})'


def rows(match=None, limit=40):
    specs = json.loads((ROOT / 'catalogue/specimens.json').read_text())['specimens']
    out = [(name, s['ref']) for name, s in specs.items() if s.get('repository') == REPO and s.get('ref')]
    if match:
        out = [(n, r) for n, r in out if match in n or match in r]
    elif limit:
        out = out[-limit:]
    return out


def table(match=None, limit=40):
    h = heads()
    lines = [f'Heads: ' + ', '.join(f'{k} {v[:8] if v else "?"}' for k, v in h.items()), '',
             '| specimen | ref | track-p | main |', '|---|---|---|---|']
    for name, ref in rows(match, limit):
        lines.append(f'| {name} | {ref[:8]} | ' + ' | '.join(position(ref, h[line]) for line in LINES) + ' |')
    return '\n'.join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--match')
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--write', action='store_true', help='write docs/LINES.md')
    a = ap.parse_args(argv)
    text = table(a.match, 0 if a.all else (60 if a.write else 40))
    if a.write:
        (ROOT / 'docs/LINES.md').write_text('# Lines of borg-reborn-rs and where each specimen stands\n\nGenerated by '
                                           '`python3 -m zoo.lines --write`; see borg-zoo#645. "behind N": the line\'s head has N '
                                           'commits the specimen does not have; "ahead N": the specimen has N commits the head does '
                                           'not have; "diverged": both.\n\n' + text + '\n')
        print('docs/LINES.md written')
    else:
        print(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
